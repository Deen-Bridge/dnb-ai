# Every route below reads or writes exactly one user's record, addressed by the
# {user_id} path segment. A plan_id is only ever looked up inside that user's
# record, so another user's plan is indistinguishable from a missing one (404).
# main.py mounts ``user_router`` behind the service API key (X-API-Key).


class UserPlannerRecord(BaseModel):
    """Everything the planner stores for one user."""

    model_config = ConfigDict(extra="ignore")

    schema_version: int = USER_RECORD_SCHEMA_VERSION
    plans: list[StoredPlan] = Field(default_factory=list, max_length=MAX_PLANS_PER_USER)
    progress: list[AyahProgress] = Field(default_factory=list, max_length=TOTAL_QURAN_AYAHS)


UserIdPath = Annotated[
    str,
    PathParam(
        min_length=1,
        max_length=MAX_USER_ID_LENGTH,
        pattern=USER_ID_PATTERN,
        description="Opaque user identifier supplied by the DeenBridge backend",
    ),
]
PlanIdPath = Annotated[str, PathParam(max_length=64, description="plan_id returned when the plan was created")]

# Serializes read-modify-write per user inside one process. A fixed pool keeps
# memory bounded no matter how many user ids are seen.
_LOCK_POOL_SIZE = 64
_user_locks = [asyncio.Lock() for _ in range(_LOCK_POOL_SIZE)]


def _user_lock(user_id: str) -> asyncio.Lock:
    index = int(hashlib.sha256(user_id.encode("utf-8")).hexdigest()[:8], 16) % _LOCK_POOL_SIZE
    return _user_locks[index]


def _storage_unavailable() -> APIException:
    return APIException(
        status_code=503,
        detail={"code": "memorization_storage_unavailable", "detail": "Planner storage is unavailable."},
        hint="Retry later. No planner data was changed by this request.",
    )


def _record_unreadable() -> APIException:
    return APIException(
        status_code=500,
        detail={"code": "memorization_record_unreadable", "detail": "Stored planner data could not be read."},
        hint="Reset this user's planner data with DELETE /memorization/users/{user_id}, then recreate the plan.",
    )


def _plan_not_found() -> APIException:
    return APIException(
        status_code=404,
        detail={"code": "memorization_plan_not_found", "detail": "Plan not found."},
        hint="No plan with this plan_id exists for this user. Create one with POST /memorization/users/{user_id}/plans.",
    )


async def _load_record(user_id: str) -> UserPlannerRecord:
    try:
        raw = await get_planner_store().load(user_id)
    except PlannerRecordCorrupt:
        raise _record_unreadable() from None
    except PlannerStoreError:
        raise _storage_unavailable() from None
    if raw is None:
        return UserPlannerRecord()
    try:
        return UserPlannerRecord.model_validate(raw)
    except ValueError:
        logger.warning("Memorization record failed validation for user_ref=%s", user_ref(user_id))
        raise _record_unreadable() from None


async def _save_record(user_id: str, record: UserPlannerRecord) -> None:
    try:
        await get_planner_store().save(user_id, record.model_dump(mode="json"))
    except PlannerStoreError:
        raise _storage_unavailable() from None


def _find_plan(record: UserPlannerRecord, plan_id: str) -> StoredPlan:
    for plan in record.plans:
        if plan.plan_id == plan_id:
            return plan
    raise _plan_not_found()


def _summary(plan: StoredPlan) -> StoredPlanSummary:
    return StoredPlanSummary(
        plan_id=plan.plan_id,
        created_at=plan.created_at,
        updated_at=plan.updated_at,
        locale=plan.locale,
        goal_summary=plan.goal_summary,
        total_target_ayahs=plan.total_target_ayahs,
        completed_ayahs=plan.completed_ayahs,
        daily_capacity_ayahs=plan.daily_capacity_ayahs,
        estimated_completion_date=plan.estimated_completion_date,
        planner_rules_version=plan.planner_rules_version,
    )


@user_router.post("/plans", response_model=GeneratePlanResponse, status_code=201)
async def create_user_plan(user_id: UserIdPath, settings: PlanSettings) -> GeneratePlanResponse:
    """Generate a plan and store it for this user (at most 10 plans; the oldest is dropped first)."""
    request = GeneratePlanRequest.model_validate({**settings.model_dump(), "user_id": user_id})
    response = MemorizationPlannerEngine.generate_plan(request)
    stored = StoredPlan(
        plan_id=response.plan_id,
        created_at=response.created_at,
        updated_at=response.created_at,
        planner_rules_version=PLANNER_RULES_VERSION,
        locale=response.locale.resolved,
        goal_summary=response.goal_summary,
        surah_numbers=[s.number for s in MemorizationPlannerEngine.resolve_target_surahs(settings.goal)],
        total_target_ayahs=response.total_target_ayahs,
        daily_capacity_ayahs=response.daily_capacity_ayahs,
        days_per_week=settings.capacity.days_per_week,
        start_date=response.weekly_schedule[0].date_str,
        estimated_completion_date=response.estimated_completion_date,
    )
    async with _user_lock(user_id):
        record = await _load_record(user_id)
        record.plans = [stored, *record.plans][:MAX_PLANS_PER_USER]
        await _save_record(user_id, record)
    logger.info("Memorization plan stored for user_ref=%s (plans=%d)", user_ref(user_id), len(record.plans))
    return response


