def _load_surah_reference() -> tuple[str | None, dict[int, dict[str, Any]]]:
    """Load the versioned surah reference table and its content hash.

    The table is generated by ``scripts/build_surah_index.py`` (see
    ``data/quran/PROVENANCE.md``). Its SHA-256 is reported in every plan's
    provenance so a response can be tied to the exact reference data used.
    """
    try:
        raw = SURAH_INDEX_FILE.read_bytes()
        entries = json.loads(raw.decode("utf-8"))
        return hashlib.sha256(raw).hexdigest(), {int(entry["number"]): entry for entry in entries}
    except (OSError, ValueError, KeyError, TypeError):
        logger.warning("Surah reference index unavailable at %s", SURAH_INDEX_RELATIVE_PATH)
        return None, {}


SURAH_INDEX_SHA256, _SURAH_REFERENCE = _load_surah_reference()


