def surah_reference_mismatches() -> list[str]:
    """Fields where the embedded table disagrees with the versioned surah index.

    Empty when consistent. Arabic names, ayah counts and revelation place are
    facts about the mushaf and must match the index exactly; transliterated
    names are display spellings and may differ (e.g. "Ta-Ha" vs "Taha").
    """
    if not _SURAH_REFERENCE:
        return ["surah_index.json unavailable"]
    problems: list[str] = []
    if set(_SURAH_REFERENCE) != set(_SURAH_DATA):
        problems.append("surah numbers differ")
    for number, info in _SURAH_DATA.items():
        reference = _SURAH_REFERENCE.get(number)
        if reference is None:
            continue
        for field in ("arabic_name", "ayah_count", "revelation_place"):
            if getattr(info, field) != reference.get(field):
                problems.append(f"{number}.{field}")
    return problems


_REFERENCE_PROBLEMS = surah_reference_mismatches()
if _REFERENCE_PROBLEMS:
    logger.error(
        "Embedded surah table disagrees with %s: %s", SURAH_INDEX_RELATIVE_PATH, ", ".join(_REFERENCE_PROBLEMS[:10])
    )


def get_surah_info(number: int) -> SurahInfo | None:
    return _SURAH_DATA.get(number)


def surah_display_name(number: int, locale: str) -> str:
    """Surah name for user-facing text: Arabic script for ``ar``, transliteration otherwise."""
    info = get_surah_info(number)
    if info is None:
        return message(locale, "celebrate.surah.fallback_name", number=number)
    return info.arabic_name if locale == "ar" else info.name


def get_juz_surahs(juz: int) -> list[SurahInfo]:
    """Return all surahs that intersect with the specified Juz."""
    if not (1 <= juz <= 30):
        return []
    return [s for s in _SURAH_DATA.values() if s.juz_start <= juz <= s.juz_end]


