def _locale_info(resolution: LocaleResolution) -> LocaleInfo:
    return LocaleInfo(
        requested=resolution.requested,
        resolved=resolution.locale,
        direction=resolution.direction,
        fallback=resolution.fallback,
        fallback_reason=resolution.fallback_reason,
    )


def _citation_reference(citation: str) -> str:
    """'Sahih al-Bukhari 5027: ...' -> 'Sahih al-Bukhari 5027'."""
    return citation.split(":", 1)[0].strip()


def _provenance(citations: list[str]) -> PlannerProvenance:
    references = list(dict.fromkeys(_citation_reference(c) for c in citations))
    return PlannerProvenance(
        planner_rules_version=PLANNER_RULES_VERSION,
        message_catalog_version=MESSAGE_CATALOG_VERSION,
        surah_reference=SurahReferenceSource(
            path=SURAH_INDEX_RELATIVE_PATH,
            sha256=SURAH_INDEX_SHA256,
            surah_count=len(_SURAH_REFERENCE),
            total_ayahs=sum(int(entry.get("ayah_count", 0)) for entry in _SURAH_REFERENCE.values()),
            numbering="Kufan (6236 ayat)",
        ),
        citations=references,
    )


class AyahRange(BaseModel):
    surah_number: int = Field(..., ge=1, le=114, description="Surah number (1-114)")
    surah_name: str = Field(..., description="Transliterated Surah name")
    surah_arabic_name: str | None = Field(
        None, description="Canonical Arabic Surah name from the versioned surah index"
    )
    start_ayah: int = Field(..., ge=1, description="Starting Ayah index")
    end_ayah: int = Field(..., ge=1, description="Ending Ayah index")
    ayah_count: int = Field(..., ge=1, description="Number of ayahs in this range")

    @model_validator(mode="after")
    def validate_range(self) -> AyahRange:
        if self.end_ayah < self.start_ayah:
            raise ValueError(f"end_ayah ({self.end_ayah}) cannot be less than start_ayah ({self.start_ayah})")
        info = get_surah_info(self.surah_number)
        if info and self.end_ayah > info.ayah_count:
            raise ValueError(f"Surah {self.surah_number} ({info.name}) only has {info.ayah_count} ayahs")
        return self


