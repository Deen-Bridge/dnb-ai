@user_router.delete("", response_model=PlannerResetResponse)
async def reset_user_planner_data(user_id: UserIdPath) -> PlannerResetResponse:
    """Permanently delete this user's plans and revision progress. Idempotent.

    Only the memorization planner record is removed; chat history and memory
    profiles are unaffected. A record that can no longer be read is still
    deleted, so reset always recovers a user from corrupt data.
    """
    store = get_planner_store()
    plans_deleted: int | None
    progress_deleted: int | None
    async with _user_lock(user_id):
        try:
            raw = await store.load(user_id)
            if raw is None:
                plans_deleted, progress_deleted = 0, 0
            else:
                existing = UserPlannerRecord.model_validate(raw)
                plans_deleted, progress_deleted = len(existing.plans), len(existing.progress)
        except PlannerRecordCorrupt:
            plans_deleted, progress_deleted = None, None
        except PlannerStoreError:
            raise _storage_unavailable() from None
        except ValueError:
            plans_deleted, progress_deleted = None, None
        try:
            existed = await store.delete(user_id)
        except PlannerStoreUnavailable:
            raise _storage_unavailable() from None
    logger.info("Memorization planner data reset for user_ref=%s (existed=%s)", user_ref(user_id), existed)
    return PlannerResetResponse(
        user_id=user_id,
        plans_deleted=plans_deleted,
        progress_entries_deleted=progress_deleted,
        message="Planner data deleted." if existed else "No planner data was stored for this user.",
    )
